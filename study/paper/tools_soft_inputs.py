"""Make generated tables and figures optional in the LaTeX draft: until analysis/report.py
has produced a file, LaTeX prints a marker instead of failing. Idempotent."""
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MACRO = (r"% tables and figures are generated by analysis/report.py; show a marker until they exist" "\n"
         r"\newcommand{\inputtable}[1]{\IfFileExists{#1}{\input{#1}}{\textit{(table pending: #1)}}}" "\n"
         r"\newcommand{\figfile}[2]{\IfFileExists{#2}{\includegraphics[#1]{#2}}{\fbox{\parbox{0.9\linewidth}{figure pending: \detokenize{#2}}}}}" "\n")

main_p = os.path.join(HERE, "main.tex")
main = open(main_p, encoding="utf-8").read()
if r"\newcommand{\inputtable}" not in main:
    anchor = r"\newcommand{\up}{upstream\xspace}"
    assert anchor in main
    main = main.replace(anchor, anchor + "\n" + MACRO)
    open(main_p, "w", encoding="utf-8", newline="\n").write(main)
    print("macro added to main.tex")

for f in glob.glob(os.path.join(HERE, "sec-*.tex")):
    s = open(f, encoding="utf-8").read()
    s2 = re.sub(r"\\input\{(\.\./results/tab_[a-z_]+\.tex)\}", r"\\inputtable{\1}", s)
    s2 = re.sub(r"\\includegraphics\[([^\]]*)\]\{(\.\./figs/[^}]+)\}", r"\\figfile{\1}{\2}", s2)
    if s2 != s:
        open(f, "w", encoding="utf-8", newline="\n").write(s2)
        print("updated", os.path.basename(f))
